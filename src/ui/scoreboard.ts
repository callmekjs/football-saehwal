/**
 * 점수판에 띄울 숫자를 정한다.
 *
 * 이 프로젝트에는 점수가 둘 있다.
 *
 * - **시뮬의 점수** — 확률로 정해진 진짜 결과다. 승패는 오직 이것으로 판정한다.
 * - **장면의 점수** — 관전 연출이 실제로 골망을 흔든 횟수다.
 *
 * 둘을 나눈 이유가 있다. 시뮬은 득점을 정한 그 순간 화면의 공이 어디 있든
 * 신경 쓰지 않는다. 숫자만 먼저 올리면 관전자는 "공은 하프라인인데 점수가
 * 올랐다"를 본다. 그래서 연출이 골을 예약해두고 진짜 공격 장면을 만든 다음에
 * 보여주고, 점수판은 그 장면을 기다린다.
 *
 * 종료 직전 골도 같은 기준을 쓴다. 마지막 장면이 남아 있으면 결과 화면이
 * 잠시 기다리고, 공 전체가 골라인을 넘은 뒤에 점수판을 올린다.
 */
export function scoreboardScore(
  /** API 호환용. 종료 뒤에도 장면보다 점수를 앞세우지 않는다. */
  _ended: boolean,
  /** 시뮬의 점수. 승패를 판정하는 진짜 값 */
  sim: readonly [number, number],
  /** 연출이 지금까지 보여준 골로 만든 점수 */
  scene: readonly [number, number],
): [number, number] {
  /**
   * 경기 중이든 종료 직후든 장면을 따라가되 **시뮬을 앞서지는 않는다.**
   *
   * 화면이 시뮬보다 늦는 것은 의도된 동작이지만, 앞서는 것은 어떤
   * 경우에도 옳지 않다 — 아직 일어나지 않은 골을 점수판이 먼저 알리는
   * 것이기 때문이다.
   */
  return [Math.min(scene[0], sim[0]), Math.min(scene[1], sim[1])]
}
